func TestRun(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name         string
		files        map[string]string
		baselineJSON string
		readOnlyBase bool
		customArgs   []string
		targetArgs   []string
		relTargets   []string
		wantCode     int
		wantOut      string
		wantErr      string
	}{
		{
			name: "healthy repository passes with missing baseline file",
			files: map[string]string{
				"pkg/clean.go":        "package pkg\n\nfunc Add(a, b int) int { return a + b }\n",
				"pkg/clean_test.go":   "package pkg\n",
				"pkg/api.gen.go":      "package pkg\n",
				"pkg/msg.pb.go":       "package pkg\n",
				"pkg/gen.go":          "// Code generated by tool; DO NOT EDIT.\npackage pkg\nfunc Huge() {}\n",
				"vendor/v/v.go":       buildLargeGoSource(1600, 160),
				"testdata/t/t.go":     buildLargeGoSource(1600, 160),
				".hidden/h.go":        buildLargeGoSource(1600, 160),
				"node_modules/m/m.go": buildLargeGoSource(1600, 160),
			},
			wantCode: 0,
			wantOut:  "Checked 2 Go file(s)",
		},
		{
			name: "violations reported when metrics exceed ceilings without baseline",
			files: map[string]string{
				"pkg/big.go":     buildLargeGoSource(1505, 155),
				"pkg/complex.go": complexAndDeepSource,
			},
			wantCode: 1,
			wantErr:  "4 ratchet violation(s) detected",
		},
		{
			name: "grandfathered baseline allows exact match and blocks growth",
			files: map[string]string{
				"pkg/big.go": buildLargeGoSource(1510, 160),
			},
			baselineJSON: `{"files":{"pkg/big.go":{"lines":1510}},"functions":{"pkg/big.go::BigFunc":{"lines":165}}}`,
			targetArgs:   []string{"pkg/big.go", "pkg/clean_test.go", "nonexistent.go"},
			relTargets:   []string{"../outside.go"},
			wantCode:     0,
			wantOut:      "Checked 1 Go file(s)",
		},
		{
			name: "update mode writes sparse baseline for outliers",
			files: map[string]string{
				"pkg/big.go":     buildLargeGoSource(1505, 155),
				"pkg/complex.go": complexAndDeepSource,
				"pkg/gen.go":     "// Code generated by generator; DO NOT EDIT.\n" + strings.Repeat("// pad\n", 400) + "package pkg\n",
			},
			customArgs: []string{"-update"},
			wantCode:   0,
			wantOut:    "wrote baseline",
		},
		{
			name: "invalid cli flag returns exit code 2",
			customArgs: []string{
				"-unknown-flag",
			},
			wantCode: 2,
			wantErr:  "flag provided but not defined",
		},
		{
			name:         "corrupt baseline json returns error",
			files:        map[string]string{"pkg/a.go": "package pkg\n"},
			baselineJSON: "{invalid-json",
			wantCode:     1,
			wantErr:      "load baseline",
		},
		{
			name:         "directory as baseline path fails loadBaseline in check mode",
			files:        map[string]string{"pkg/a.go": "package pkg\n"},
			readOnlyBase: true,
			wantCode:     1,
			wantErr:      "load baseline",
		},
		{
			name: "syntax error in go file fails check",
			files: map[string]string{
				"pkg/broken.go": "package pkg\nfunc (",
			},
			wantCode: 1,
			wantErr:  "code-health: check:",
		},
		{
			name: "syntax error in go file fails update mode",
			files: map[string]string{
				"pkg/broken.go": "package pkg\nfunc (",
			},
			customArgs: []string{"-update"},
			wantCode:   1,
			wantErr:    "code-health: analyze:",
		},
		{
			name: "unwritable baseline path fails update mode",
			files: map[string]string{
				"pkg/a.go": "package pkg\n",
			},
			readOnlyBase: true,
			customArgs:   []string{"-update"},
			wantCode:     1,
			wantErr:      "write baseline",
		},
		{
			name: "missing root directory fails target collection",
			customArgs: []string{
				"-root", "/nonexistent-code-health-root-dir-xyz",
			},
			wantCode: 1,
			wantErr:  "collect targets",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			dir := t.TempDir()
			for rel, content := range tc.files {
				full := filepath.Join(dir, filepath.FromSlash(rel))
				if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
					t.Fatalf("mkdir: %v", err)
				}
				if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
					t.Fatalf("write file: %v", err)
				}
			}

			basePath := filepath.Join(dir, ".code-health-baseline.json")
			if tc.readOnlyBase {
				basePath = dir
			} else if tc.baselineJSON != "" {
				if err := os.WriteFile(basePath, []byte(tc.baselineJSON), 0o644); err != nil {
					t.Fatalf("write baseline: %v", err)
				}
			}

			args := []string{"-root", dir, "-baseline", basePath}
			args = append(args, tc.customArgs...)
			for _, targ := range tc.targetArgs {
				args = append(args, filepath.Join(dir, filepath.FromSlash(targ)))
			}
			args = append(args, tc.relTargets...)
			if len(tc.customArgs) == 2 && tc.customArgs[0] == "-root" {
				args = tc.customArgs
			} else if len(tc.customArgs) == 1 && tc.customArgs[0] == "-unknown-flag" {
				args = tc.customArgs
			}

			var stdout, stderr bytes.Buffer
			code := run(args, &stdout, &stderr)
			if code != tc.wantCode {
				t.Fatalf("run() code = %d, want %d (stdout=%q, stderr=%q)", code, tc.wantCode, stdout.String(), stderr.String())
			}
			if tc.wantOut != "" && !strings.Contains(stdout.String(), tc.wantOut) {
				t.Errorf("stdout %q does not contain %q", stdout.String(), tc.wantOut)
			}
			if tc.wantErr != "" && !strings.Contains(stderr.String(), tc.wantErr) {
				t.Errorf("stderr %q does not contain %q", stderr.String(), tc.wantErr)
			}
		})
	}
}

func TestExprName(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		expr ast.Expr
		want string
	}{
		{
			name: "parenthesized receiver",
			expr: &ast.ParenExpr{X: &ast.Ident{Name: "Srv"}},
			want: "Srv",
		},
		{
			name: "fallback unknown expression",
			expr: &ast.BasicLit{},
			want: "recv",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			if got := exprName(tc.expr); got != tc.want {
				t.Errorf("exprName() = %q, want %q", got, tc.want)
			}
		})
	}
}
