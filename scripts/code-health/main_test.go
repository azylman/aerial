func TestEditSimilarity(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		a    []string
		b    []string
		want float64
	}{
		{
			name: "both empty",
			a:    nil,
			b:    nil,
			want: 0.0,
		},
		{
			name: "left empty",
			a:    nil,
			b:    []string{"x"},
			want: 0.0,
		},
		{
			name: "right empty",
			a:    []string{"x"},
			b:    nil,
			want: 0.0,
		},
		{
			name: "identical slices",
			a:    []string{"a", "b", "c"},
			b:    []string{"a", "b", "c"},
			want: 1.0,
		},
		{
			name: "single substitution",
			a:    []string{"a", "b", "c"},
			b:    []string{"a", "x", "c"},
			want: 2.0 / 3.0,
		},
		{
			name: "single insertion",
			a:    []string{"a", "b"},
			b:    []string{"a", "x", "b"},
			want: 2.0 / 3.0,
		},
		{
			name: "completely disjoint",
			a:    []string{"a", "b"},
			b:    []string{"c", "d"},
			want: 0.0,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got := editSimilarity(tc.a, tc.b)
			if diff := got - tc.want; diff > 1e-6 || diff < -1e-6 {
				t.Errorf("editSimilarity() = %f, want %f", got, tc.want)
			}
		})
	}
}
