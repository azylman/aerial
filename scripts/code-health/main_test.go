func buildLargeGoSource(fileLines, funcLines int) string {
	var sb strings.Builder
	sb.WriteString("package sample\n\nfunc ForwardDecl()\n\nfunc BigFunc(x int) int {\n")
	for range funcLines {
		sb.WriteString("\tx++\n")
	}
	sb.WriteString("\treturn x\n}\n")
	curLines := strings.Count(sb.String(), "\n")
	for i := curLines; i < fileLines; i++ {
		sb.WriteString("// padding line\n")
	}
	return sb.String()
}

// buildCloneFuncSource renders the clone fixture function; gap adds an extra if between the select loop and the switch.
func buildCloneFuncSource(name string, gap bool) string {
	gapStmt := ""
	if gap {
		gapStmt = "\tif x == 42 {\n\t\treturn 42\n\t}\n"
	}
	return `func ` + name + `(x int, ch chan int) int {
	if x > 0 {
		println("positive")
	} else {
		println("non-positive")
	}
	for i := 0; i < x; i++ {
		select {
		case <-ch:
			return -1
		default:
			break
		}
	}
` + gapStmt + `	switch x {
	case 1:
		defer println("defer 1")
	default:
		defer println("defer default")
	}
	for range []int{1} {
		println("loop")
	}
	return x
}
`
}

func buildCallAndTypeSwitchSource() string {
	return `package sample

type Worker struct{}

func (w *Worker) Process(x any, fn func()) {
	switch x.(type) {
	case int:
		w.Process(nil, nil)
	default:
		fn()
	}
}
`
}

func buildClosureFieldsSource() string {
	var sb strings.Builder
	sb.WriteString("type Suite struct {\n")
	for _, name := range []string{"run", "check", "extraCheck", "setup", "validate", "validator", "verify", "lookup"} {
		sb.WriteString("\t" + name + " " + "func()\n")
	}
	sb.WriteString("\tother string\n}\n")
	return sb.String()
}

