type testRunCase struct {
	name                     string
	files                    map[string]string
	baselineJSON             string
	configJSON               string
	readOnlyBase             bool
	customArgs               []string
	rawArgs                  []string // replaces the generated -root/-baseline prefix and targets
	targetArgs               []string
	relTargets               []string
	wantBaselineFiles        map[string]int
	wantBaselineBlankAssigns map[string]int
	wantBaselineRootFiles    map[string]int
	wantFileContains         map[string]string
	wantCode                 int
	wantOut                  string
	wantErr                  string
}

func TestRun(t *testing.T) {
	t.Parallel()

	for _, tc := range testRunCases() {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			runTestRunCase(t, tc)
		})
	}
}

func testRunCases() []testRunCase {
	base := testRunBaseCases()
	errs := testRunBaseErrorCases()
	clones := testRunCloneCases()
	targets := testRunTargetCases()
	roots := testRunRootFileCases()
	configs := testRunConfigCases()
	blank := testRunBlankDiscardCases()
	all := make([]testRunCase, 0, len(base)+len(errs)+len(clones)+len(targets)+len(roots)+len(configs)+len(blank))
	all = append(all, base...)
	all = append(all, errs...)
	all = append(all, clones...)
	all = append(all, targets...)
	all = append(all, roots...)
	all = append(all, configs...)
	all = append(all, blank...)
	return all
}

